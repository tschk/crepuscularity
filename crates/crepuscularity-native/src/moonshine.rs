//! Moonshine JSX emitter, promoted from the CLI so external Rust projects can call it.
//!
//! HTML is the real production path (`build_site_wasm`). `--emit moonshine` writes
//! a real `@tschk/crepus-moonshine` app entry under `dist/`.

use crate::ir::{
    html_input_type, html_tag, implicit_aria_label, implicit_form_name, ViewIr, ViewNode, ViewStyle,
};
use crate::scoped_expression::{
    bound_value_expr, checked_expr, component_local_name, expression_runtime, label_expr,
    property_access, slider_value_expr, tab_index_expr, tab_selected_expr, text_expr, LocalBinding,
};
use crate::utils::js_str;

/// Shared preamble emitted by both entry points: the `Fragment` import used by
/// `ForEach` and the `toArray` guard so a missing/non-array scope value renders
/// nothing instead of throwing.
const RUNTIME_PREAMBLE: &str = r#"import { Fragment } from "react";

const toArray = (v: unknown): any[] => (Array.isArray(v) ? v : []);
"#;

fn rotation_runtime(children: &str) -> String {
    if !children.contains("<__CrepusRotatingText") {
        return String::new();
    }
    format!(
        r#"import {{ useEffect as __crepusUseEffect, useRef as __crepusUseRef, type ComponentPropsWithoutRef as __CrepusSpanProps }} from "react";
{}
function __CrepusRotatingText({{ phrases, interval, ...props }}: {{ phrases: string[]; interval: number }} & __CrepusSpanProps<"span">) {{
  const node = __crepusUseRef<HTMLSpanElement>(null);
  // IR phrases and intervals are static; parent renders retain the mounted rotation.
  const initial = __crepusUseRef({{ phrases, interval }});
  __crepusUseEffect(() => {{
    if (node.current) return __crepusRotate(node.current, initial.current)?.destroy;
  }}, []);
  return <span {{...props}} ref={{node}} />;
}}
"#,
        crate::scoped_expression::ROTATING_TEXT_RUNTIME
    )
}

/// The emitted props contract shared by both the app and component emitters:
/// `<Name>Scope`, `<Name>Handlers`, `<Name>Props`, and the destructured
/// function signature that opens the component body.
fn props_contract(name: &str) -> String {
    format!(
        // `any`, not `unknown`: template expressions compare and dereference
        // scope values (`count > 0`, `user.name`), and `unknown` makes every one
        // of those a TS18046 error in the consumer's build. The template
        // language is untyped, so the boundary is where the typing stops.
        r#"export type {name}Scope = Record<string, any>;
export type {name}Handlers = Record<string, (...args: any[]) => void>;
export type {name}Props = {{ scope?: {name}Scope; handlers?: {name}Handlers }};
"#
    )
}

/// Emit a Moonshine app entry as real JSX, preserving the original class tokens
/// as `className` so UnoCSS/Tailwind styles the output.
///
/// Output is valid TSX: `App` + optional `mount` helper using `@tschk/moonshine/react`.
pub fn emit_moonshine_app(ir: &ViewIr) -> String {
    let locals: Vec<LocalBinding> = Vec::new();
    let children: String = ir
        .root
        .iter()
        .map(|n| emit_jsx_node(n, 3, &locals))
        .collect::<Vec<_>>()
        .join("\n");
    let expression_runtime = expression_runtime(&children);
    let rotation_runtime = rotation_runtime(&children);
    let contract = props_contract("App");
    let mut body = format!(
        r#"// Generated by crepus web build --emit moonshine
import {{ createApp }} from "@tschk/moonshine/react";
{RUNTIME_PREAMBLE}
{rotation_runtime}
{contract}
export function App({{ scope = {{}}, handlers = {{}} }}: AppProps) {{
{expression_runtime}
  return (
    <div data-crepus-root="true">
{children}
    </div>
  );
}}
"#
    );
    body.push_str(
        r##"
// Optional mount helper for Vite entry
export function mount(selector = "#app") {
  createApp({ root: App }).mount(selector);
}

export default App;
"##,
    );
    body
}

/// Emit the same JSX tree as [`emit_moonshine_app`] but as a named, importable
/// component instead of an app entry: no `createApp` import, no `mount` helper.
/// JavaScript keywords keep their public export name through a safe internal alias.
pub fn emit_moonshine_component(ir: &ViewIr, component_name: &str) -> String {
    let locals: Vec<LocalBinding> = Vec::new();
    let children: String = ir
        .root
        .iter()
        .map(|n| emit_jsx_node(n, 3, &locals))
        .collect::<Vec<_>>()
        .join("\n");
    let expression_runtime = expression_runtime(&children);
    let rotation_runtime = rotation_runtime(&children);
    let contract = props_contract(component_name);
    let local_name = component_local_name(
        component_name,
        &[
            "Fragment",
            "__CrepusRotatingText",
            "__crepusRotate",
            "__crepusUseEffect",
            "__crepusUseRef",
            "__CrepusSpanProps",
        ],
    );
    let function_export = if local_name == component_name {
        "export "
    } else {
        ""
    };
    let named_export = if local_name == component_name {
        String::new()
    } else if component_name == "default" {
        format!("Object.defineProperty({local_name}, \"name\", {{ value: \"default\" }});\n")
    } else {
        format!("Object.defineProperty({local_name}, \"name\", {{ value: \"{component_name}\" }});\nexport {{ {local_name} as {component_name} }};\n")
    };
    format!(
        r#"// Generated React component by Crepuscularity
{RUNTIME_PREAMBLE}
{rotation_runtime}
{contract}
{function_export}function {local_name}({{ scope = {{}}, handlers = {{}} }}: {component_name}Props) {{
{expression_runtime}
  return (
    <div data-crepus-root="true">
{children}
    </div>
  );
}}

{named_export}export default {local_name};
"#
    )
}

/// A string-valued JSX attribute, written the way a person writes it:
/// `name="value"`. The braced form is only used when the value cannot sit
/// inside a quoted literal, since `name={"value"}` is legal but not idiomatic.
fn attr(name: &str, value: &str) -> String {
    let needs_expr = value
        .chars()
        .any(|c| matches!(c, '"' | '\\' | '&') || (c as u32) < 0x20);
    if needs_expr {
        format!(" {name}={{{}}}", js_str(value))
    } else {
        format!(" {name}=\"{value}\"")
    }
}

/// A JSX text child, written literally rather than as `{"..."}`. Characters
/// JSX reads as markup or as an HTML entity force the braced form, because
/// literal text containing them would not round-trip.
fn jsx_text(content: &str) -> String {
    let needs_expr = content.is_empty()
        || content != content.trim()
        || content
            .chars()
            .any(|c| matches!(c, '{' | '}' | '<' | '>' | '&') || (c as u32) < 0x20);
    if needs_expr {
        format!("{{{}}}", js_str(content))
    } else {
        content.to_string()
    }
}

/// Source identity and class tokens preserved on the node.
fn identity_attrs(style: Option<&ViewStyle>) -> String {
    let mut attrs = style
        .and_then(|style| style.id.as_ref())
        .map(|id| attr("id", id))
        .unwrap_or_default();
    if let Some(label) = style.and_then(|style| style.aria_label.as_ref()) {
        attrs.push_str(&attr("aria-label", label));
    }
    if let Some(style) = style {
        for (attribute, value) in [
            ("min", &style.form_min),
            ("max", &style.form_max),
            ("step", &style.form_step),
        ] {
            if let Some(value) = value {
                attrs.push_str(&attr(attribute, value));
            }
        }
    }
    if let Some(name) = style.and_then(|style| style.form_name.as_ref()) {
        attrs.push_str(&attr("name", name));
    }
    if style.is_some_and(|style| style.required == Some(true)) {
        attrs.push_str(" required");
    }
    attrs
}

fn class_tokens(style: Option<&ViewStyle>) -> String {
    style
        .filter(|style| !style.classes.is_empty())
        .map(|style| attr("className", &style.classes.join(" ")))
        .unwrap_or_default()
}

fn class_attr(style: Option<&ViewStyle>) -> String {
    let mut attrs = identity_attrs(style);
    if let Some(style) = style {
        if style.html_tag.as_deref() == Some("label") {
            if let Some(target) = &style.html_for {
                attrs.push_str(&attr("htmlFor", target));
            }
        }
    }
    if style.is_some_and(|style| style.html_display_contents == Some(true)) {
        attrs.push_str(" style={{display:\"contents\"}}");
    }
    attrs.push_str(&class_tokens(style));
    attrs
}

fn opt_attr(name: &str, value: Option<&String>) -> String {
    match value {
        Some(v) => attr(name, v),
        None => String::new(),
    }
}

/// Rewrite expression references using the shared framework lexer.
fn scope_expr(expr: &str, locals: &[LocalBinding]) -> String {
    crate::js_expr::scope_expr(expr, locals, "scope.")
}

fn on_click_attr(name: &str) -> String {
    format!(
        " onClick={{() => {}?.()}}",
        property_access("handlers", name)
    )
}

fn dom_event_attr(js_event: &str, name: &str) -> String {
    format!(
        " {js_event}={{(event) => {}?.(event)}}",
        property_access("handlers", name)
    )
}

fn opt_on_click(v: Option<&String>) -> String {
    v.map(|n| on_click_attr(n)).unwrap_or_default()
}

fn opt_dom_event(js_event: &str, v: Option<&String>) -> String {
    v.map(|n| dom_event_attr(js_event, n)).unwrap_or_default()
}

fn opt_on_long_press(v: Option<&String>) -> String {
    v.map(|n| attr("data-crepus-on-long-press", n))
        .unwrap_or_default()
}

fn emit_children(children: &[ViewNode], indent: usize, locals: &[LocalBinding]) -> String {
    children
        .iter()
        .map(|c| emit_jsx_node(c, indent, locals))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Wrap `children` in `tag`, or self-close when there are none.
fn element(
    tag: &str,
    attrs: &str,
    children: &[ViewNode],
    indent: usize,
    locals: &[LocalBinding],
) -> String {
    let pad = "  ".repeat(indent);
    if children.is_empty() {
        return format!("{pad}<{tag}{attrs} />");
    }
    let inner = emit_children(children, indent + 1, locals);
    format!("{pad}<{tag}{attrs}>\n{inner}\n{pad}</{tag}>")
}

/// `{COND ? (<>...then...</>) : (<>...else...</> | null)}`.
fn emit_if(
    condition: &str,
    then_children: &[ViewNode],
    else_children: Option<&Vec<ViewNode>>,
    indent: usize,
    locals: &[LocalBinding],
) -> String {
    let pad = "  ".repeat(indent);
    let cond = scope_expr(condition, locals);
    let then_jsx = format!(
        "{pad}  <>\n{}\n{pad}  </>",
        emit_children(then_children, indent + 2, locals)
    );
    let (else_open, else_body, else_close) = match else_children {
        None => ("", "null".to_string(), ""),
        Some(ec) => (
            "(\n",
            format!(
                "{pad}  <>\n{}\n{pad}  </>",
                emit_children(ec, indent + 2, locals)
            ),
            "\n{pad})",
        ),
    };
    let else_close = else_close.replace("{pad}", &pad);
    format!("{pad}{{{cond} ? (\n{then_jsx}\n{pad}) : {else_open}{else_body}{else_close}}}")
}

/// `{toArray(scope.BIND).map((ITEM, index) => (<Fragment key={index}>...</Fragment>))}`.
fn emit_for_each(
    bind: &str,
    item_name: &str,
    item_body: &[ViewNode],
    indent: usize,
    locals: &[LocalBinding],
) -> String {
    let pad = "  ".repeat(indent);
    let bind_expr = scope_expr(bind, locals);
    let binding = LocalBinding::loop_item(item_name, locals.len());
    let item_name = binding.variable.clone();
    let index_name = format!("_crepusIndex{}", locals.len());
    let mut inner_locals = locals.to_vec();
    inner_locals.push(binding);
    let inner = emit_children(item_body, indent + 2, &inner_locals);
    format!(
        "{pad}{{toArray({bind_expr}).map(({item_name}, {index_name}) => (\n{pad}  <Fragment key={{{index_name}}}>\n{inner}\n{pad}  </Fragment>\n{pad}))}}"
    )
}

fn emit_jsx_node(node: &ViewNode, indent: usize, locals: &[LocalBinding]) -> String {
    let pad = "  ".repeat(indent);
    match node {
        ViewNode::Text {
            content,
            bind,
            style,
        } => {
            let body = match bind {
                Some(b) => format!("{{{}}}", text_expr(b, locals, "scope.")),
                None => jsx_text(content),
            };
            let tag = html_tag(style.as_ref(), "span");
            format!("{pad}<{tag}{}>{}</{tag}>", class_attr(style.as_ref()), body)
        }
        ViewNode::Link {
            href,
            href_bind,
            target,
            rel,
            style,
            children,
        } => {
            let attrs = format!(
                "{}{}{}{}",
                href_bind.as_ref().map(|bind| format!(" href={{{}}}", text_expr(bind, locals, "scope."))).unwrap_or_else(|| attr("href", href)),
                opt_attr("target", target.as_ref()),
                opt_attr("rel", rel.as_ref()),
                class_attr(style.as_ref())
            );
            element("a", &attrs, children, indent, locals)
        }
        ViewNode::Stack {
            on_long_press,
            style,
            children,
            ..
        } => {
            let attrs = format!("{}{}", class_attr(style.as_ref()), opt_on_long_press(on_long_press.as_ref()));
            element(html_tag(style.as_ref(), "div"), &attrs, children, indent, locals)
        }
        ViewNode::Scroll { style, children, on_long_press, .. } => {
            let attrs = format!("{}{}", class_attr(style.as_ref()), opt_on_long_press(on_long_press.as_ref()));
            element(html_tag(style.as_ref(), "div"), &attrs, children, indent, locals)
        }
        ViewNode::Dropzone {
            on_drop,
            style,
            children,
            ..
        } => {
            let dispatch = on_drop.as_ref().map(|name| {
                format!("{}?.(event);", property_access("handlers", name))
            }).unwrap_or_default();
            let attrs = format!(
                "{} onDragOver={{(event) => event.preventDefault()}} onDrop={{(event) => {{ event.preventDefault(); {dispatch} }}}}",
                class_attr(style.as_ref())
            );
            element("div", &attrs, children, indent, locals)
        }
        ViewNode::List {
            ordered,
            style,
            children,
        } => element(
            if *ordered { "ol" } else { "ul" },
            &class_attr(style.as_ref()),
            children,
            indent,
            locals,
        ),
        ViewNode::ListItem {
            on_long_press,
            style,
            children,
        } => {
            let attrs = format!("{}{}", class_attr(style.as_ref()), opt_on_long_press(on_long_press.as_ref()));
            element("li", &attrs, children, indent, locals)
        }
        ViewNode::Button {
            label,
            label_parts,
            on_click,
            on_long_press,
            style,
        } => format!(
            "{pad}<button type=\"button\"{}{}{}>{}</button>",
            class_attr(style.as_ref()),
            opt_on_click(on_click.as_ref()),
            opt_on_long_press(on_long_press.as_ref()),
            label_expr(label_parts, locals, "scope.").map(|expr| format!("{{{expr}}}")).unwrap_or_else(|| jsx_text(label))
        ),
        ViewNode::Badge { label, tone, style, .. } => format!(
            "{pad}<span{}{}>{}</span>",
            class_attr(style.as_ref()),
            opt_attr("data-tone", tone.as_ref()),
            jsx_text(label)
        ),
        ViewNode::Divider { style, .. } => {
            format!("{pad}<hr{} />", class_attr(style.as_ref()))
        }
        ViewNode::Spacer { style, .. } => {
            format!("{pad}<div aria-hidden=\"true\"{} />", class_attr(style.as_ref()))
        }
        ViewNode::Image {
            src,
            src_bind,
            alt,
            on_long_press,
            style,
            ..
        } => format!(
            "{pad}<img{}{}{}{} />",
            src_bind.as_ref().map(|bind| format!(" src={{{}}}", text_expr(bind, locals, "scope."))).unwrap_or_else(|| attr("src", src)),
            attr("alt", alt.as_deref().unwrap_or("")),
            class_attr(style.as_ref()),
            opt_on_long_press(on_long_press.as_ref())
        ),
        ViewNode::WebView { src, style } => format!(
            "{pad}<iframe{}{} />",
            attr("src", src),
            class_attr(style.as_ref())
        ),
        ViewNode::Toggle {
            label,
            bind,
            checked,
            on_change,
            on_long_press,
            style,
            ..
        } => format!(
            "{pad}<button type=\"button\" role=\"switch\" aria-checked={{{}}}{}{}{}>{}</button>",
            checked_expr(bind.as_deref(), *checked, locals, "scope."),
            class_attr(style.as_ref()),
            opt_dom_event("onClick", on_change.as_ref()),
            opt_on_long_press(on_long_press.as_ref()),
            jsx_text(label)
        ),
        ViewNode::Checkbox {
            label,
            bind,
            checked,
            on_change,
            style,
            ..
        } => format!(
            "{pad}<label{}>\n{pad}  <input type=\"checkbox\" {}={{{}}}{} />\n{pad}  {}\n{pad}</label>",
            class_tokens(style.as_ref()),
            if bind.as_deref().unwrap_or_default().trim().is_empty() { "defaultChecked" } else { "checked" },
            checked_expr(bind.as_deref(), *checked, locals, "scope."),
            identity_attrs(style.as_ref()) + &opt_attr("value", style.as_ref().and_then(|style| style.form_value.as_ref())) + &opt_dom_event("onChange", on_change.as_ref()),
            jsx_text(label)
        ),
        ViewNode::Slider {
            label,
            bind,
            value,
            min,
            max,
            step,
            on_change,
            style,
        } => {
            let (value, min, max, step) =
                crate::codegen::shared::slider_values(*value, *min, *max, *step);
            let value_expr = slider_value_expr(bind.as_deref(), value, min, max, locals, "scope.");
            let value_attr = if bind.as_deref().unwrap_or_default().trim().is_empty() {
                "defaultValue"
            } else {
                "value"
            };
            let step = step
                .map(|step| format!(" step={{{step}}}"))
                .unwrap_or_else(|| attr("step", "any"));
            format!(
                "{pad}<input type=\"range\" {value_attr}={{{value_expr}}} min={{{min}}} max={{{max}}}{step}{}{}{} />",
                opt_attr("aria-label", implicit_aria_label(style.as_ref(), label.as_ref())),
                class_attr(style.as_ref()),
                opt_dom_event("onChange", on_change.as_ref())
            )
        }
        ViewNode::Progress {
            label, value, max, style,
        } => {
            let (value, max) = crate::codegen::shared::progress_values(*value, *max);
            format!(
                "{pad}<progress max={{{max}}} value={{{value}}}{}{} />",
                opt_attr("aria-label", implicit_aria_label(style.as_ref(), label.as_ref())),
                class_attr(style.as_ref())
            )
        }
        ViewNode::Meter {
            label, value, min, max, style,
        } => {
            let (value, min, max) = crate::codegen::shared::meter_values(*value, *min, *max);
            format!(
                "{pad}<meter min={{{min}}} max={{{max}}} value={{{value}}}{}{} />",
                opt_attr("aria-label", implicit_aria_label(style.as_ref(), label.as_ref())),
                class_attr(style.as_ref())
            )
        }
        ViewNode::Input {
            placeholder,
            bind,
            secure,
            multiline,
            on_input,
            on_change,
            style,
        } => {
            let bound_value = bound_value_expr(bind, locals, "scope.");
            let initial_value = style.as_ref().and_then(|style| style.form_value.as_ref()).map(|value| js_str(value));
            let value = bound_value
                .as_ref()
                .or(initial_value.as_ref())
                .map(|expr| format!(" defaultValue={{{expr}}}"))
                .unwrap_or_default();
            // Native change preserves commit semantics; React onChange fires while editing.
            let reference = if bound_value.is_some() || on_change.is_some() {
                format!(
                    " ref={{__crepusInputRef({}, handlers, {})}}",
                    bound_value.as_deref().unwrap_or("undefined"),
                    on_change
                        .as_ref()
                        .map(|action| js_str(action))
                        .unwrap_or_else(|| "undefined".into())
                )
            } else {
                String::new()
            };
            let on_input_attr = on_input
                .as_ref()
                .map(|action| {
                    format!(
                        " onInput={{(event) => {}?.(event.nativeEvent)}}",
                        property_access("handlers", action)
                    )
                })
                .unwrap_or_default();
            let cls = class_attr(style.as_ref());
            let ph = attr("placeholder", placeholder);
            let name = opt_attr("name", implicit_form_name(style.as_ref(), Some(bind)));
            if *multiline {
                format!("{pad}<textarea{value}{ph}{name}{cls}{reference}{on_input_attr} />")
            } else {
                let ty = html_input_type(style.as_ref(), *secure);
                format!("{pad}<input type=\"{ty}\"{value}{ph}{name}{cls}{reference}{on_input_attr} />")
            }
        }
        ViewNode::Picker {
            options,
            bind,
            on_change,
            style,
        } => {
            let value = bound_value_expr(bind, locals, "scope.")
                .map(|expr| format!(" value={{{expr}}}"))
                .unwrap_or_default();
            let opts: String = options
                .iter()
                .map(|o| {
                    format!(
                        "{pad}  <option{}>{}</option>",
                        attr("value", &o.value),
                        jsx_text(&o.label)
                    )
                })
                .collect::<Vec<_>>()
                .join("\n");
            format!(
                "{pad}<select{value}{}{}{}>\n{opts}\n{pad}</select>",
                opt_attr("name", implicit_form_name(style.as_ref(), Some(bind))),
                class_attr(style.as_ref()),
                opt_dom_event("onChange", on_change.as_ref())
            )
        }
        ViewNode::FilePicker {
            label,
            accept,
            multiple,
            on_pick,
            style,
        } => {
            let accept_attr = if accept.is_empty() {
                String::new()
            } else {
                attr("accept", &accept.join(","))
            };
            let multiple_attr = if *multiple { " multiple" } else { "" };
            format!(
                "{pad}<label{}>\n{pad}  <input type=\"file\"{accept_attr}{multiple_attr}{} />\n{pad}  {}\n{pad}</label>",
                class_tokens(style.as_ref()),
                identity_attrs(style.as_ref()) + &opt_dom_event("onChange", on_pick.as_ref()),
                jsx_text(label)
            )
        }
        ViewNode::SlotRotate {
            phrases,
            interval_ms,
            style,
        } => format!(
            "{pad}<__CrepusRotatingText phrases={{{}}} interval={{{interval_ms}}}{} data-interval-ms={{{interval_ms}}}{}>{}</__CrepusRotatingText>",
            serde_json::to_string(phrases).unwrap().replace('<', "\\u003c"),
            attr("data-crepus-slot-rotate", &phrases.join("|")),
            class_attr(style.as_ref()),
            jsx_text(phrases.first().map(String::as_str).unwrap_or(""))
        ),
        ViewNode::Tabs {
            bind,
            tabs,
            on_change,
            style,
        } => {
            let mut wrapper_style = style.clone();
            let tablist_name = wrapper_style
                .as_mut()
                .and_then(|style| style.aria_label.take());
            let tablist_label = attr("aria-label", tablist_name.as_deref().unwrap_or("Tabs"));
            let mut cls = class_attr(wrapper_style.as_ref());
            if bind.trim().is_empty() {
                cls.push_str(&attr("data-crepus-tabs-unbound", "true"));
            }
            let buttons: String = tabs
                .iter()
                .enumerate()
                .map(|(index, t)| {
                    let selected = tab_selected_expr(bind, tabs, index, locals, "scope.");
                    let tab_index = tab_index_expr(bind, tabs, index, locals, "scope.");
                    let onclick = match on_change {
                        Some(name) => format!(" onClick={{() => {}?.({})}}", property_access("handlers", name), js_str(&t.value)),
                        None => String::new(),
                    };
                    format!(
                        "{pad}    <button type=\"button\" role=\"tab\" aria-selected={{{selected}}} tabIndex={{{tab_index}}}{onclick}>{}</button>",
                        jsx_text(&t.label)
                    )
                })
                .collect::<Vec<_>>()
                .join("\n");
            let panels: String = tabs
                .iter()
                .enumerate()
                .map(|(index, t)| {
                    let selected = tab_selected_expr(bind, tabs, index, locals, "scope.");
                    format!(
                        "{pad}  <div role=\"tabpanel\" hidden={{!({selected})}} tabIndex={{0}}>\n{}\n{pad}  </div>",
                        emit_children(&t.children, indent + 2, locals)
                    )
                })
                .collect::<Vec<_>>()
                .join("\n");
            format!(
                "{pad}<div{cls} ref={{__crepusTabsRef}}>\n{pad}  <div role=\"tablist\"{tablist_label} onKeyDown={{__crepusTabsKey}} tabIndex={{-1}}>\n{buttons}\n{pad}  </div>\n{panels}\n{pad}</div>"
            )
        }
        ViewNode::If {
            condition,
            then_children,
            else_children,
            ..
        } => emit_if(condition, then_children, else_children.as_ref(), indent, locals),
        ViewNode::ForEach {
            bind,
            item_name,
            item_body,
            ..
        } => emit_for_each(bind, item_name, item_body, indent, locals),
    }
}

