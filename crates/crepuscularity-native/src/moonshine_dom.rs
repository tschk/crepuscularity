//! Direct Moonshine DOM/SSR source generation, without JSX or a host framework.

use crate::ir::{
    html_input_type, implicit_aria_label, implicit_form_name, ViewIr, ViewNode, ViewStyle,
};
use crate::scoped_expression::{
    bound_value_expr, checked_expr, expression_runtime, label_expr, property_access,
    slider_value_expr, tab_index_expr, tab_selected_expr, text_expr, LocalBinding,
};

/// Emit an importable browser component. Mount inside `render` from Moonshine DOM.
/// `scope` can be a record or a reactive accessor; scripts are not executed.
pub fn emit_moonshine_dom_component(ir: &ViewIr, name: &str) -> Result<String, String> {
    emit_component(ir, name, false)
}

/// Emit an importable server component for Moonshine's `renderToString`.
pub fn emit_moonshine_ssr_component(ir: &ViewIr, name: &str) -> Result<String, String> {
    emit_component(ir, name, true)
}

fn emit_component(ir: &ViewIr, name: &str, server: bool) -> Result<String, String> {
    let mut chars = name.chars();
    if !chars
        .next()
        .is_some_and(|ch| ch.is_ascii_alphabetic() || matches!(ch, '_' | '$'))
        || !chars.all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '_' | '$'))
        || name == "default"
    {
        return Err("component name must be a JavaScript identifier other than default".into());
    }
    let children = children(&ir.root, &[])?;
    let mut runtime = expression_runtime(&children);
    let mut rotation_import = "";
    if children.contains("__crepusSlotRotate(") {
        if server {
            runtime.push_str("function __crepusSlotRotate(phrases: string[], _interval: number): string { return phrases[0] ?? \"\"; }\n");
        } else {
            rotation_import = "import { createRotatingText as __crepusSlotRotate } from \"@tschk/moonshine-dom/rotating-text\";\n";
        }
    }
    let target = if server { "ssr" } else { "dom" };
    let child_type = if server { "SSRChild" } else { "DOMChild" };
    Ok(format!(
        r#"// Generated by Crepuscularity; template scripts are not executed.
import {{ h, type {child_type} as Child }} from "@tschk/moonshine-dom/{target}";
import {{ For, Show }} from "@tschk/moonshine-dom/control";
{rotation_import}

export type CrepusDomProps = {{
  scope?: Record<string, any> | (() => Record<string, any>);
  handlers?: Record<string, (...args: any[]) => void>;
}};

function __CrepusComponent(props: CrepusDomProps = {{}}) {{
  const scope = () => typeof props.scope === "function" ? props.scope() : props.scope ?? {{}};
  const handlers = () => props.handlers ?? {{}};
  const toArray = (value: unknown): any[] => globalThis.Array.isArray(value) ? value : [];
{runtime}
  return h("div", {{ "data-crepus-root": "true" }}, {children});
}}

export {{ __CrepusComponent as {name} }};
export default __CrepusComponent;
"#
    ))
}

fn js(value: &str) -> String {
    serde_json::Value::String(value.into()).to_string()
}

fn style_props(style: Option<&ViewStyle>) -> Vec<String> {
    let mut props = vec![];
    if let Some(style) = style {
        if style.html_display_contents == Some(true) {
            props.push("style: {display: \"contents\"}".into());
        }
        for (attribute, value) in [
            ("min", &style.form_min),
            ("max", &style.form_max),
            ("step", &style.form_step),
        ] {
            if let Some(value) = value {
                props.push(format!("{attribute}: {}", js(value)));
            }
        }
        if let Some(name) = &style.form_name {
            props.push(format!("name: {}", js(name)));
        }
        if style.required == Some(true) {
            props.push("required: true".into());
        }
        if let Some(label) = &style.aria_label {
            props.push(format!("\"aria-label\": {}", js(label)));
        }
        if let Some(id) = &style.id {
            props.push(format!("id: {}", js(id)));
        }
        if style.html_tag.as_deref() == Some("label") {
            if let Some(target) = &style.html_for {
                props.push(format!("for: {}", js(target)));
            }
        }
        if !style.classes.is_empty() {
            props.push(format!("class: {}", js(&style.classes.join(" "))));
        }
    }
    props
}

fn element(tag: &str, props: Vec<String>, child: Option<String>) -> String {
    let child = child.map(|child| format!(", {child}")).unwrap_or_default();
    format!("h({}, {{ {} }}{child})", js(tag), props.join(", "))
}

fn event(props: &mut Vec<String>, event: &str, handler: Option<&str>, argument: &str) {
    if let Some(handler) = handler {
        props.push(format!(
            "{}: (event: Event) => {}?.({argument})",
            js(event),
            property_access("handlers()", handler)
        ));
    }
}

fn long_press(props: &mut Vec<String>, handler: Option<&String>) {
    if let Some(handler) = handler {
        props.push(format!("\"data-crepus-on-long-press\": {}", js(handler)));
    }
}

fn children(nodes: &[ViewNode], locals: &[LocalBinding]) -> Result<String, String> {
    Ok(format!(
        "[{}]",
        nodes
            .iter()
            .map(|node| node_expr(node, locals))
            .collect::<Result<Vec<_>, _>>()?
            .join(",\n")
    ))
}

fn node_expr(node: &ViewNode, locals: &[LocalBinding]) -> Result<String, String> {
    let expr = |source: &str| crate::scoped_expression::scope_expr(source, locals, "scope().");
    Ok(match node {
        ViewNode::Text {
            content,
            bind,
            style,
        } => {
            let text = bind
                .as_ref()
                .map(|bind| format!("() => {}", text_expr(bind, locals, "scope().")))
                .unwrap_or_else(|| js(content));
            element(
                crate::ir::html_tag(style.as_ref(), "span"),
                style_props(style.as_ref()),
                Some(text),
            )
        }
        ViewNode::Stack {
            children: nodes,
            on_long_press,
            style,
            ..
        }
        | ViewNode::ListItem {
            children: nodes,
            on_long_press,
            style,
        } => {
            let mut props = style_props(style.as_ref());
            long_press(&mut props, on_long_press.as_ref());
            element(
                if matches!(node, ViewNode::ListItem { .. }) {
                    "li"
                } else {
                    crate::ir::html_tag(style.as_ref(), "div")
                },
                props,
                Some(children(nodes, locals)?),
            )
        }
        ViewNode::Dropzone {
            children: nodes,
            on_drop,
            style,
            ..
        } => {
            let mut props = style_props(style.as_ref());
            props.push("onDragOver: (event: Event) => event.preventDefault()".into());
            let dispatch = on_drop
                .as_ref()
                .map(|handler| format!("{}?.(event);", property_access("handlers()", handler)))
                .unwrap_or_default();
            props.push(format!(
                "onDrop: (event: Event) => {{ event.preventDefault(); {dispatch} }}"
            ));
            element("div", props, Some(children(nodes, locals)?))
        }
        ViewNode::Scroll {
            children: nodes,
            style,
            on_long_press,
            ..
        } => {
            let mut props = style_props(style.as_ref());
            long_press(&mut props, on_long_press.as_ref());
            element(
                crate::ir::html_tag(style.as_ref(), "div"),
                props,
                Some(children(nodes, locals)?),
            )
        }
        ViewNode::List {
            ordered,
            children: nodes,
            style,
        } => element(
            if *ordered { "ol" } else { "ul" },
            style_props(style.as_ref()),
            Some(children(nodes, locals)?),
        ),
        ViewNode::Button {
            label,
            label_parts,
            on_click,
            on_long_press,
            style,
        } => {
            let mut props = style_props(style.as_ref());
            props.push("type: \"button\"".into());
            event(&mut props, "onClick", on_click.as_deref(), "");
            long_press(&mut props, on_long_press.as_ref());
            let text = label_expr(label_parts, locals, "scope().")
                .map(|value| format!("() => {value}"))
                .unwrap_or_else(|| js(label));
            element("button", props, Some(text))
        }
        ViewNode::Input {
            placeholder,
            bind,
            multiline,
            secure,
            on_input,
            on_change,
            style,
        } => {
            let mut props = style_props(style.as_ref());
            props.push(format!("placeholder: {}", js(placeholder)));
            if let Some(name) = implicit_form_name(style.as_ref(), Some(bind)) {
                props.push(format!("name: {}", js(name)));
            }
            if !multiline {
                props.push(format!(
                    "type: {}",
                    js(html_input_type(style.as_ref(), *secure))
                ));
            }
            if let Some(value) = bound_value_expr(bind, locals, "scope().") {
                props.push(format!("value: () => {value}"));
            } else if let Some(value) = style.as_ref().and_then(|style| style.form_value.as_ref()) {
                props.push(format!("defaultValue: {}", js(value)));
            }
            event(&mut props, "onInput", on_input.as_deref(), "event");
            event(&mut props, "onChange", on_change.as_deref(), "event");
            element(if *multiline { "textarea" } else { "input" }, props, None)
        }
        ViewNode::Checkbox {
            label,
            bind,
            checked,
            on_change,
            style,
        }
        | ViewNode::Toggle {
            label,
            bind,
            checked,
            on_change,
            style,
            ..
        } => {
            let checked_prop = if matches!(node, ViewNode::Checkbox { .. })
                && bind.as_deref().unwrap_or_default().trim().is_empty()
            {
                format!("defaultChecked: {checked}")
            } else {
                format!(
                    "checked: () => {}",
                    checked_expr(bind.as_deref(), *checked, locals, "scope()."),
                )
            };
            let mut props = vec!["type: \"checkbox\"".into(), checked_prop];
            if matches!(node, ViewNode::Checkbox { .. }) {
                if let Some(value) = style.as_ref().and_then(|style| style.form_value.as_ref()) {
                    props.push(format!("value: {}", js(value)));
                }
            }
            if matches!(node, ViewNode::Toggle { .. }) {
                props.push("role: \"switch\"".into());
            }
            event(&mut props, "onChange", on_change.as_deref(), "event");
            let mut wrapper_style = style.clone();
            if let Some(style) = &mut wrapper_style {
                if let Some(name) = style.form_name.take() {
                    props.push(format!("name: {}", js(&name)));
                }
                if style.required.take() == Some(true) {
                    props.push("required: true".into());
                }
                if let Some(label) = style.aria_label.take() {
                    props.push(format!("\"aria-label\": {}", js(&label)));
                }
                if let Some(id) = style.id.take() {
                    props.push(format!("id: {}", js(&id)));
                }
            }
            let mut label_props = style_props(wrapper_style.as_ref());
            if let ViewNode::Toggle { on_long_press, .. } = node {
                long_press(&mut label_props, on_long_press.as_ref());
            }
            element(
                "label",
                label_props,
                Some(format!(
                    "[{}, {}]",
                    element("input", props, None),
                    js(label)
                )),
            )
        }
        ViewNode::FilePicker {
            label,
            accept,
            multiple,
            on_pick,
            style,
        } => {
            let mut field_style = style.clone();
            if let Some(style) = &mut field_style {
                style.classes.clear();
                style.html_tag = None;
                style.html_display_contents = None;
            }
            let mut props = style_props(field_style.as_ref());
            props.push("type: \"file\"".into());
            if !accept.is_empty() {
                props.push(format!("accept: {}", js(&accept.join(","))));
            }
            if *multiple {
                props.push("multiple: true".into());
            }
            event(&mut props, "onChange", on_pick.as_deref(), "event");
            let label_props = style
                .as_ref()
                .filter(|style| !style.classes.is_empty())
                .map(|style| vec![format!("class: {}", js(&style.classes.join(" ")))])
                .unwrap_or_default();
            element(
                "label",
                label_props,
                Some(format!(
                    "[{}, {}]",
                    element("input", props, None),
                    js(label)
                )),
            )
        }
        ViewNode::Tabs {
            bind,
            tabs,
            on_change,
            style,
        } => {
            let mut wrapper_style = style.clone();
            let label = wrapper_style
                .as_mut()
                .and_then(|style| style.aria_label.take());
            let mut props = style_props(wrapper_style.as_ref());
            props.push("ref: __crepusTabsRef".into());
            props.push("\"data-crepus-tabs-id\": __crepusTabsPrefix".into());
            if bind.trim().is_empty() {
                props.push("\"data-crepus-tabs-unbound\": \"true\"".into());
            }
            let mut buttons = Vec::new();
            let mut panels = Vec::new();
            for (index, tab) in tabs.iter().enumerate() {
                let selected = tab_selected_expr(bind, tabs, index, locals, "scope().");
                let tab_id = format!("__crepusTabsPrefix + \"-tab-{index}\"");
                let panel_id = format!("__crepusTabsPrefix + \"-panel-{index}\"");
                let mut button_props = vec![
                    "type: \"button\"".into(),
                    "role: \"tab\"".into(),
                    format!("id: {tab_id}"),
                    format!("\"aria-controls\": {panel_id}"),
                    format!("\"aria-selected\": () => globalThis.String({selected})"),
                    format!(
                        "tabIndex: () => {}",
                        tab_index_expr(bind, tabs, index, locals, "scope().")
                    ),
                ];
                event(
                    &mut button_props,
                    "onClick",
                    on_change.as_deref(),
                    &js(&tab.value),
                );
                buttons.push(element("button", button_props, Some(js(&tab.label))));
                panels.push(element(
                    "div",
                    vec![
                        "role: \"tabpanel\"".into(),
                        "tabIndex: 0".into(),
                        format!("id: {panel_id}"),
                        format!("\"aria-labelledby\": {tab_id}"),
                        format!("hidden: () => !({selected})"),
                    ],
                    Some(children(&tab.children, locals)?),
                ));
            }
            let list = element(
                "div",
                vec![
                    "role: \"tablist\"".into(),
                    format!("\"aria-label\": {}", js(label.as_deref().unwrap_or("Tabs"))),
                    "onKeyDown: __crepusTabsKey".into(),
                    "tabIndex: -1".into(),
                ],
                Some(format!("[{}]", buttons.join(", "))),
            );
            let content = format!("[{list}, {}]", panels.join(", "));
            let root = element("div", props, Some(content));
            format!("(() => {{ const __crepusTabsPrefix = \"crepus-tabs-\" + (globalThis.crypto?.randomUUID?.() ?? globalThis.Math.random().toString(36).slice(2)); return {root}; }})()")
        }
        ViewNode::Picker {
            bind,
            options,
            on_change,
            style,
        } => {
            let mut props = style_props(style.as_ref());
            if let Some(value) = bound_value_expr(bind, locals, "scope().") {
                props.push(format!("value: () => {value}"));
            }
            event(&mut props, "onChange", on_change.as_deref(), "event");
            let options = options
                .iter()
                .enumerate()
                .map(|(index, option)| {
                    let mut props = vec![format!("value: {}", js(&option.value))];
                    if option.value.is_empty() {
                        // shortcut: retain explicit empty values until the host handles equal option.value writes.
                        props.push(
                            "ref: (option: any) => option.setAttribute(\"value\", \"\")".into(),
                        );
                    }
                    if bind.trim().is_empty() && index == 0 {
                        props.push("selected: true".into());
                    }
                    element("option", props, Some(js(&option.label)))
                })
                .collect::<Vec<_>>()
                .join(", ");
            element("select", props, Some(format!("[{options}]")))
        }
        ViewNode::Slider {
            label,
            bind,
            value,
            min,
            max,
            step,
            on_change,
            style,
        } => {
            let (value, min, max, step) =
                crate::codegen::shared::slider_values(*value, *min, *max, *step);
            let mut props = style_props(style.as_ref());
            props.extend([
                "type: \"range\"".into(),
                format!("min: {min}"),
                format!("max: {max}"),
            ]);
            props.push(format!(
                "step: {}",
                step.map(|value| value.to_string())
                    .unwrap_or_else(|| js("any"))
            ));
            if bind.as_deref().unwrap_or_default().trim().is_empty() {
                props.push(format!("defaultValue: {value}"));
            } else {
                props.push(format!(
                    "value: () => {}",
                    slider_value_expr(bind.as_deref(), value, min, max, locals, "scope().")
                ));
            }
            if let Some(label) = implicit_aria_label(style.as_ref(), label.as_ref()) {
                props.push(format!("\"aria-label\": {}", js(label)));
            }
            event(&mut props, "onChange", on_change.as_deref(), "event");
            element("input", props, None)
        }
        ViewNode::Progress {
            label,
            value,
            max,
            style,
        } => {
            let (value, max) = crate::codegen::shared::progress_values(*value, *max);
            let mut props = style_props(style.as_ref());
            props.extend([format!("max: {max}"), format!("value: {value}")]);
            if let Some(label) = implicit_aria_label(style.as_ref(), label.as_ref()) {
                props.push(format!("\"aria-label\": {}", js(label)));
            }
            element("progress", props, None)
        }
        ViewNode::Meter {
            label,
            value,
            min,
            max,
            style,
        } => {
            let (value, min, max) = crate::codegen::shared::meter_values(*value, *min, *max);
            let mut props = style_props(style.as_ref());
            props.extend([
                format!("min: {min}"),
                format!("max: {max}"),
                format!("value: {value}"),
            ]);
            if let Some(label) = implicit_aria_label(style.as_ref(), label.as_ref()) {
                props.push(format!("\"aria-label\": {}", js(label)));
            }
            element("meter", props, None)
        }
        ViewNode::Link {
            href,
            href_bind,
            target,
            rel,
            children: nodes,
            style,
        } => {
            let mut props = style_props(style.as_ref());
            props.push(format!(
                "href: {}",
                href_bind
                    .as_ref()
                    .map(|bind| format!("() => {}", text_expr(bind, locals, "scope().")))
                    .unwrap_or_else(|| js(href))
            ));
            if let Some(value) = target {
                props.push(format!("target: {}", js(value)));
            }
            if let Some(value) = rel {
                props.push(format!("rel: {}", js(value)));
            }
            element("a", props, Some(children(nodes, locals)?))
        }
        ViewNode::WebView { src, style } => {
            let mut props = style_props(style.as_ref());
            props.push(format!("src: {}", js(src)));
            element("iframe", props, None)
        }
        ViewNode::Image {
            src,
            src_bind,
            alt,
            on_long_press,
            style,
            ..
        } => {
            let mut props = style_props(style.as_ref());
            props.push(format!(
                "src: {}",
                src_bind
                    .as_ref()
                    .map(|bind| format!("() => {}", text_expr(bind, locals, "scope().")))
                    .unwrap_or_else(|| js(src))
            ));
            props.push(format!("alt: {}", js(alt.as_deref().unwrap_or(""))));
            long_press(&mut props, on_long_press.as_ref());
            element("img", props, None)
        }
        ViewNode::Badge { label, tone, style } => {
            let mut props = style_props(style.as_ref());
            if let Some(tone) = tone {
                props.push(format!("\"data-tone\": {}", js(tone)));
            }
            element("span", props, Some(js(label)))
        }
        ViewNode::Divider { style, .. } => element("hr", style_props(style.as_ref()), None),
        ViewNode::Spacer { style, .. } => {
            let mut props = style_props(style.as_ref());
            props.push("\"aria-hidden\": \"true\"".into());
            element("div", props, None)
        }
        ViewNode::If {
            condition,
            then_children,
            else_children,
            ..
        } => {
            crepuscularity_core::eval::validate_expr(condition)
                .map_err(|error| error.to_string())?;
            format!(
                "Show<any, Child>({{ when: () => ({}), children: () => {}, fallback: () => {} }})",
                expr(condition),
                children(then_children, locals)?,
                children(else_children.as_deref().unwrap_or_default(), locals)?
            )
        }
        ViewNode::ForEach {
            bind,
            item_name,
            item_body,
            ..
        } => {
            crate::scoped_expression::validate_collection_expr(bind)
                .map_err(|error| error.to_string())?;
            let local = LocalBinding::loop_item(item_name, locals.len());
            let variable = local.variable.clone();
            let mut nested = locals.to_vec();
            nested.push(local);
            let value =
                bound_value_expr(bind, locals, "scope().").unwrap_or_else(|| "undefined".into());
            format!(
                "For<any, Child>({{ each: () => toArray({value}), children: ({variable}: any) => {} }})",
                children(item_body, &nested)?
            )
        }
        ViewNode::SlotRotate {
            phrases,
            interval_ms,
            style,
        } => element(
            "span",
            style_props(style.as_ref()),
            Some(format!(
                "__crepusSlotRotate({}, {interval_ms})",
                serde_json::to_string(phrases).map_err(|error| error.to_string())?
            )),
        ),
    })
}

#[cfg(test)]
mod dynamic_url_tests {
    use super::*;
    #[test]
    fn media_url_getters_preserve_loop_and_root_reactivity() {
        let locals = [LocalBinding::loop_item("row", 0)];
        for node in [
            ViewNode::Image {
                src: "snapshot.png".into(),
                src_bind: Some("row.url".into()),
                alt: None,
                placeholder: None,
                on_long_press: None,
                style: None,
            },
            ViewNode::Link {
                href: "snapshot.html".into(),
                href_bind: Some("row.url".into()),
                target: None,
                rel: None,
                style: None,
                children: vec![],
            },
        ] {
            let output = node_expr(&node, &locals).unwrap();
            assert!(
                output.contains("() => __crepusText(") && output.contains("_crepusItem0"),
                "{output}"
            );
            assert!(!output.contains("snapshot."), "{output}");
        }
        let node = ViewNode::Image {
            src: String::new(),
            src_bind: Some("url".into()),
            alt: None,
            placeholder: None,
            on_long_press: None,
            style: None,
        };
        let output = node_expr(&node, &[]).unwrap();
        assert!(
            output.contains("src: () => __crepusText(") && output.contains("scope()"),
            "{output}"
        );
    }
}
