//! Smoke test: `crepus ios new` lays out Crepus project + SwiftPM files.

use std::process::Command;

#[test]
#[cfg_attr(
    windows,
    ignore = "default desktop crepus.exe does not spawn reliably on Windows CI"
)]
fn ios_new_scaffold_writes_crepus_project_and_native_shell() {
    let dir = tempfile::tempdir().expect("tempdir");
    let name = "crepus-ios-cli-test";
    let root = dir.path().join(name);

    let out = Command::new(env!("CARGO_BIN_EXE_crepus"))
        .args(["ios", "new", name])
        .current_dir(dir.path())
        .output()
        .expect("spawn crep ios new");

    assert!(
        out.status.success(),
        "stderr:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );

    let crepus = std::fs::read_to_string(root.join("crepus.toml")).unwrap();
    assert!(crepus.contains("[ios]"));
    assert!(crepus.contains("scheme = \"CrepusIosCliTestApp\""));
    assert!(root.join("NativeShell").join("Package.swift").is_file());
    assert!(root
        .join("NativeShell")
        .join("Sources")
        .join("NativeShell")
        .join("ViewIrModels.swift")
        .is_file());
    let generated = Command::new(env!("CARGO_BIN_EXE_crepus"))
        .args(["ios", "generate", "--dir", root.to_str().unwrap()])
        .output()
        .expect("generate project");
    assert!(generated.status.success());
    let project =
        std::fs::read_to_string(root.join("CrepusIosCliTestApp.xcodeproj/project.pbxproj"))
            .expect("read project");
    assert!(project.contains("XCLocalSwiftPackageReference"));
    assert!(project.contains("GENERATE_INFOPLIST_FILE = YES"));

    let fixture = std::fs::read_to_string(
        root.join("NativeShell")
            .join("Sources")
            .join("NativeShell")
            .join("fixture.json"),
    )
    .unwrap();
    assert!(fixture.contains("\"version\": 3"));

    // Exercise naming edge case: NativeShell package name collision → HostApp target
    let coll = dir.path().join("native-shell");
    let out2 = Command::new(env!("CARGO_BIN_EXE_crepus"))
        .args(["ios", "new", "native-shell"])
        .current_dir(dir.path())
        .output()
        .expect("spawn");
    assert!(out2.status.success());
    let tom = std::fs::read_to_string(coll.join("crepus.toml")).unwrap();
    assert!(tom.contains("scheme = \"NativeShellHostApp\""));
}

#[cfg(unix)]
mod explicit_spec {
    use super::*;
    use std::fs;
    use std::os::unix::fs::PermissionsExt;
    use std::path::{Path, PathBuf};

    struct Fixture {
        _temp: tempfile::TempDir,
        root: PathBuf,
        caller: PathBuf,
        bin: PathBuf,
        dump_log: PathBuf,
        generate_log: PathBuf,
        build_log: PathBuf,
    }

    impl Fixture {
        fn new() -> Self {
            let temp = tempfile::tempdir().unwrap();
            let root = temp.path().join("app with spaces");
            let caller = temp.path().join("outside caller");
            let bin = temp.path().join("tool stubs");
            for dir in [&root, &caller, &bin] {
                fs::create_dir_all(dir).unwrap();
            }
            fs::write(root.join("crepus.toml"), "[ios]\nscheme = \"Custom\"\n").unwrap();
            fs::create_dir(root.join("spec files")).unwrap();
            fs::write(
                root.join("spec files/custom spec.yml"),
                "name: Selected Project\n",
            )
            .unwrap();
            let fixture = Self {
                dump_log: temp.path().join("dump.log"),
                generate_log: temp.path().join("generate.log"),
                build_log: temp.path().join("build.log"),
                _temp: temp,
                root,
                caller,
                bin,
            };
            // Labelled executable stubs verify CLI routing without invoking Apple tools.
            fixture.tool(
                "xcodegen",
                r#"if [ "$1" = dump ]; then
  printf '%s\n' "$PWD" "$@" > "$SPEC_DUMP_LOG"
  printf '{"name":"Selected Project"}'
  exit 0
fi
printf '%s\n' "$PWD" "$@" > "$SPEC_GENERATE_LOG"
mkdir -p 'Selected Project.xcodeproj'
printf 'generated by stub' > 'Selected Project.xcodeproj/project.pbxproj'
"#,
            );
            fixture.tool(
                "xcodebuild",
                r#"printf '%s\n' "$PWD" "$@" > "$SPEC_BUILD_LOG"
"#,
            );
            fixture
        }

        fn tool(&self, name: &str, body: &str) {
            let path = self.bin.join(name);
            fs::write(&path, format!("#!/bin/sh\n{body}")).unwrap();
            fs::set_permissions(path, fs::Permissions::from_mode(0o755)).unwrap();
        }

        fn run(&self, command: &str, spec: &Path) -> std::process::Output {
            let mut path = vec![self.bin.clone()];
            path.extend(std::env::split_paths(
                &std::env::var_os("PATH").unwrap_or_default(),
            ));
            Command::new(env!("CARGO_BIN_EXE_crepus"))
                .args(["ios", command, "--dir"])
                .arg(&self.root)
                .arg("--spec")
                .arg(spec)
                .current_dir(&self.caller)
                .env("PATH", std::env::join_paths(path).unwrap())
                .env("SPEC_DUMP_LOG", &self.dump_log)
                .env("SPEC_GENERATE_LOG", &self.generate_log)
                .env("SPEC_BUILD_LOG", &self.build_log)
                .output()
                .unwrap()
        }

        fn assert_generate_args(&self, spec: &Path) {
            let dump = fs::read_to_string(&self.dump_log).unwrap();
            assert_eq!(
                dump.lines().collect::<Vec<_>>(),
                vec![
                    fs::canonicalize(&self.root).unwrap().to_str().unwrap(),
                    "dump",
                    "--spec",
                    spec.to_str().unwrap(),
                    "--type",
                    "json",
                ]
            );
            let lines = fs::read_to_string(&self.generate_log).unwrap();
            assert_eq!(
                lines.lines().collect::<Vec<_>>(),
                vec![
                    fs::canonicalize(&self.root).unwrap().to_str().unwrap(),
                    "generate",
                    "--spec",
                    spec.to_str().unwrap(),
                    "--project",
                    ".",
                ]
            );
        }
    }

    #[test]
    fn explicit_relative_and_absolute_specs_use_xcodegen_from_the_project_root() {
        for absolute in [false, true] {
            let fixture = Fixture::new();
            let spec = if absolute {
                fixture.root.join("spec files/custom spec.yml")
            } else {
                PathBuf::from("spec files/custom spec.yml")
            };
            let output = fixture.run("generate", &spec);
            assert!(
                output.status.success(),
                "{}",
                String::from_utf8_lossy(&output.stderr)
            );
            fixture.assert_generate_args(&spec);
            assert_eq!(
                fs::read_to_string(
                    fixture
                        .root
                        .join("Selected Project.xcodeproj/project.pbxproj")
                )
                .unwrap(),
                "generated by stub"
            );
            assert!(!fixture.build_log.exists());
        }
    }

    #[test]
    fn explicit_spec_build_uses_the_resolved_project_instead_of_an_existing_decoy() {
        let fixture = Fixture::new();
        let decoy = fixture.root.join("Custom.xcodeproj");
        fs::create_dir(&decoy).unwrap();
        fs::write(decoy.join("project.pbxproj"), "existing built-in project").unwrap();
        let spec = Path::new("spec files/custom spec.yml");
        let output = fixture.run("build", spec);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        fixture.assert_generate_args(spec);
        let build = fs::read_to_string(&fixture.build_log).unwrap();
        let args = build.lines().collect::<Vec<_>>();
        assert_eq!(
            args[0],
            fs::canonicalize(&fixture.root).unwrap().to_str().unwrap()
        );
        assert!(args
            .windows(2)
            .any(|pair| pair == ["-project", "Selected Project.xcodeproj"]));
        assert!(args.windows(2).any(|pair| pair == ["-scheme", "Custom"]));
        assert_eq!(args.last(), Some(&"build"));
        assert_eq!(
            fs::read_to_string(decoy.join("project.pbxproj")).unwrap(),
            "existing built-in project"
        );
    }

    #[test]
    fn missing_spec_and_generator_failure_preserve_existing_project_and_do_not_build() {
        for command in ["generate", "build"] {
            for missing in [false, true] {
                let fixture = Fixture::new();
                let project = fixture.root.join("Custom.xcodeproj");
                fs::create_dir(&project).unwrap();
                fs::write(project.join("project.pbxproj"), "keep original").unwrap();
                fixture.tool(
                    "xcodegen",
                    r#"if [ "$1" = dump ]; then
  printf '{"name":"Selected Project"}'
  exit 0
fi
printf 'invoked' > "$SPEC_GENERATE_LOG"
exit 7
"#,
                );
                let spec = Path::new(if missing {
                    "missing spec.yml"
                } else {
                    "spec files/custom spec.yml"
                });
                let output = fixture.run(command, spec);
                assert!(!output.status.success());
                let stderr = String::from_utf8_lossy(&output.stderr);
                assert!(
                    stderr.contains(if missing {
                        "spec not found"
                    } else {
                        "xcodegen generate failed"
                    }),
                    "{stderr}"
                );
                assert_eq!(fixture.generate_log.exists(), !missing);
                assert!(!fixture.build_log.exists());
                assert_eq!(
                    fs::read_to_string(project.join("project.pbxproj")).unwrap(),
                    "keep original"
                );
            }
        }
    }

    #[test]
    fn failed_or_invalid_spec_dump_stops_before_generation_and_build() {
        for command in ["generate", "build"] {
            for (body, diagnostic) in [
                (
                    "printf 'dump diagnostic' >&2\nexit 9\n",
                    "xcodegen dump failed: dump diagnostic",
                ),
                ("printf 'not JSON'\n", "invalid xcodegen dump JSON"),
                ("printf '{}'\n", "valid project name"),
                ("printf '{\"name\":\"../outside\"}'\n", "valid project name"),
            ] {
                let fixture = Fixture::new();
                let project = fixture.root.join("Custom.xcodeproj");
                fs::create_dir(&project).unwrap();
                fs::write(project.join("project.pbxproj"), "keep original").unwrap();
                fixture.tool(
                    "xcodegen",
                    &format!(
                    "if [ \"$1\" != dump ]; then touch \"$SPEC_GENERATE_LOG\"; exit 99; fi\n{body}"
                ),
                );
                let output = fixture.run(command, Path::new("spec files/custom spec.yml"));
                assert!(!output.status.success());
                let stderr = String::from_utf8_lossy(&output.stderr);
                assert!(stderr.contains(diagnostic), "{stderr}");
                assert!(!fixture.generate_log.exists());
                assert!(!fixture.build_log.exists());
                assert_eq!(
                    fs::read_to_string(project.join("project.pbxproj")).unwrap(),
                    "keep original"
                );
            }
        }
    }
}

#[test]
fn ios_new_dotted_name_keeps_directory_and_emits_valid_swift_stem() {
    let directory = tempfile::tempdir().unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_crepus"))
        .args(["ios", "new", "my.app"])
        .current_dir(directory.path())
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let root = directory.path().join("my.app");
    let source = std::fs::read_to_string(root.join("App/App.swift")).unwrap();
    assert!(source.contains("struct MyAppApp: App {"), "{source}");
    let manifest = std::fs::read_to_string(root.join("crepus.toml")).unwrap();
    let config: toml::Value = toml::from_str(&manifest).unwrap();
    assert_eq!(config["ios"]["scheme"].as_str(), Some("MyAppApp"));
    assert!(root.join("NativeShell/Package.swift").is_file());
}
