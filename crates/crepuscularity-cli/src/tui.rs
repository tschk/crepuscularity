//! `crepus tui` — Terminal User Interface apps with Ratatui.
//!
//! Scaffold and build TUI applications that render `.crepus` templates in the terminal
//! using Ratatui for layout and Crossterm for input handling.

use std::path::Path;
use std::process::Command;

#[cfg(feature = "tui")]
use console::style;

use crate::build_options::BuildOptions;
use crate::cli::TuiCommands;
use crate::scaffold;
use crate::ui;

/// Caret-style version requirement injected into scaffolded TUI apps for
/// `crepuscularity-tui`. Keep this aligned with the published `crepuscularity-tui`
/// minor; pre-1.0 caret on `0.x.y` resolves to `>=0.x.y, <0.(x+1).0`.
const SCAFFOLD_TUI_VERSION: &str = "0.5.0";

pub fn execute(cmd: TuiCommands) {
    match cmd {
        TuiCommands::New { name } => scaffold_tui_app(&name),
        TuiCommands::Build { build, extra } => {
            build_tui_app(build.into_options_or_exit(), &extra);
        }
        TuiCommands::Run { build, extra } => {
            run_tui_app(build.into_options_or_exit(), &extra);
        }
        TuiCommands::Preview { file } => {
            #[cfg(feature = "tui")]
            preview_tui_template(&file);
            #[cfg(not(feature = "tui"))]
            {
                let _ = &file;
                ui::error("TUI preview not compiled in. Rebuild crepus with --features tui.");
            }
        }
    }
}

fn scaffold_tui_app(name: &str) {
    scaffold::validate_project_name(name).unwrap_or_else(|e| ui::error(e));
    let dir = Path::new(name);

    // Create directory structure
    scaffold::create_project_dir(dir)
        .unwrap_or_else(|e| ui::error(&format!("failed to create project directory: {e}")));

    let cargo_toml = format!(
        r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2021"

[dependencies]
# Bump these as needed; the scaffold is pinned to the version of `crepus` you
# scaffolded with.
crepuscularity-tui = "{tui_version}"
ratatui = {{ version = "0.30", default-features = false, features = ["crossterm"] }}
crossterm = "0.29"
anyhow = "1.0"
"#,
        name = name,
        tui_version = SCAFFOLD_TUI_VERSION,
    );

    let main_rs = r###"//! Generated by `crepus tui new`. Edit `app.crepus` and run `crepus tui run`
//! (or `cargo run`). The template hot-reloads on save.

use std::time::Duration;

use crepuscularity_tui::{HotTemplate, ReloadOutcome};
use crossterm::event::{Event, KeyCode};
use ratatui::DefaultTerminal;

fn main() -> anyhow::Result<()> {
    let mut hot = HotTemplate::watch("app.crepus").map_err(|e| anyhow::anyhow!(e))?;
    hot.template_mut()
        .set("title", "My TUI App")
        .set("message", "Hello from Crepuscularity!")
        .set("quit_hint", "Press 'q' to quit");

    let mut terminal = ratatui::init();
    let result = run(&mut terminal, &mut hot);
    ratatui::restore();
    result
}

fn run(terminal: &mut DefaultTerminal, hot: &mut HotTemplate) -> anyhow::Result<()> {
    loop {
        terminal.draw(|frame| {
            let _ = hot.poll_and_draw_full(frame);
        })?;

        if crossterm::event::poll(Duration::from_millis(100))? {
            if let Event::Key(key) = crossterm::event::read()? {
                if matches!(key.code, KeyCode::Char('q') | KeyCode::Esc) {
                    return Ok(());
                }
            }
        }

        // Avoid an unused-variant warning if a future ReloadOutcome::Error is added.
        let _ = ReloadOutcome::Unchanged;
    }
}
"###;
    scaffold::write_file(&dir.join("Cargo.toml"), &cargo_toml)
        .unwrap_or_else(|e| ui::error(&format!("failed to write Cargo.toml: {e}")));

    // Create src directory
    scaffold::ensure_dir(&dir.join("src"))
        .unwrap_or_else(|e| ui::error(&format!("failed to create src directory: {e}")));

    // Write src/main.rs
    scaffold::write_file(&dir.join("src/main.rs"), main_rs)
        .unwrap_or_else(|e| ui::error(&format!("failed to write src/main.rs: {e}")));

    // Create a basic .crepus template file
    let template_content = r#"div bg-black text-white flex flex-col gap-4
  div text-2xl font-bold text-green-400
    "Welcome to {title}"
  div text-lg
    "{message}"
  div text-sm text-gray-500
    "{quit_hint}"
"#;

    scaffold::write_file(&dir.join("app.crepus"), template_content)
        .unwrap_or_else(|e| ui::error(&format!("failed to write app.crepus: {e}")));

    ui::success(&format!(
        "Created new TUI app '{}' in directory '{}'",
        name,
        dir.display()
    ));
    eprintln!("Run 'cd {} && cargo run' to start the app", name);
}

fn build_tui_app(options: BuildOptions, extra: &[String]) {
    ensure_cargo_project_for_tui();
    let mut cmd = Command::new("cargo");
    cmd.arg("build");
    options.apply_profile_to_command(&mut cmd);
    cmd.args(extra);
    delegate_to_cargo(cmd, "build");
}

fn run_tui_app(options: BuildOptions, extra: &[String]) {
    ensure_cargo_project_for_tui();
    let mut cmd = Command::new("cargo");
    cmd.arg("run");
    options.apply_profile_to_command(&mut cmd);
    if !extra.is_empty() {
        cmd.arg("--").args(extra);
    }
    delegate_to_cargo(cmd, "run");
}

fn ensure_cargo_project_for_tui() {
    if !Path::new("Cargo.toml").exists() {
        ui::error(
            "no Cargo.toml in the current directory. Run `crepus tui build|run` from the \
             root of a TUI app scaffolded with `crepus tui new <name>`.",
        );
    }
}

fn delegate_to_cargo(mut cmd: Command, verb: &str) {
    match cmd.status() {
        Ok(status) if status.success() => {}
        Ok(status) => {
            std::process::exit(status.code().unwrap_or(1));
        }
        Err(e) => {
            ui::error(&format!(
                "failed to invoke `cargo {verb}`: {e}. Is the Rust toolchain installed and on PATH?"
            ));
        }
    }
}

/// Live-preview a `.crepus` template in the current terminal.
///
/// Sets up crossterm raw mode via `ratatui::init`, watches the file for
/// changes via [`crepuscularity_tui::HotTemplate`], and re-renders on each
/// save. `q` or `Esc` exits cleanly; `r` forces a reload. A `context.toml`
/// next to the template supplies variables initially and after successful reloads.
#[cfg(feature = "tui")]
fn preview_tui_template(path: &Path) {
    use crepuscularity_tui::{HotTemplate, ReloadOutcome};
    use ratatui::crossterm::event::{self, Event, KeyCode, KeyEventKind};
    use std::time::{Duration, Instant};

    if !path.exists() {
        ui::error(&format!("file not found: {}", path.display()));
    }

    let mut hot = match HotTemplate::watch(path) {
        Ok(h) => h,
        Err(e) => ui::error(&format!("could not load template: {e}")),
    };

    refresh_tui_preview_context(&mut hot);

    eprintln!(
        "{} previewing {} (q/Esc to quit, r to force reload)",
        style("crepus tui").dim(),
        style(path.display().to_string()).cyan().bold()
    );

    let mut terminal = ratatui::init();
    let mut last_reload: Option<(Instant, ReloadOutcome)> = None;

    let result: Result<(), String> = loop {
        match reload_tui_preview(&mut hot, false) {
            ReloadOutcome::Unchanged => {}
            other => last_reload = Some((Instant::now(), other)),
        }
        if let Err(e) = terminal.draw(|frame| {
            let _ = hot.draw_full(frame);
        }) {
            break Err(format!("terminal draw: {e}"));
        }

        if matches!(event::poll(Duration::from_millis(100)), Ok(true)) {
            match event::read() {
                Ok(Event::Key(key)) if key.kind == KeyEventKind::Press => match key.code {
                    KeyCode::Char('q') | KeyCode::Esc => break Ok(()),
                    KeyCode::Char('r') => {
                        last_reload = Some((Instant::now(), reload_tui_preview(&mut hot, true)));
                    }
                    _ => {}
                },
                Ok(_) => {}
                Err(e) => break Err(format!("event read: {e}")),
            }
        }

        if let Some((t, _)) = &last_reload {
            if t.elapsed() > Duration::from_secs(2) {
                last_reload = None;
            }
        }
    };
    ratatui::restore();

    if let Some((_, ReloadOutcome::Error(msg))) = last_reload {
        eprintln!("{} {}", style("⚠").yellow(), msg);
    }
    if let Err(e) = result {
        ui::error(&e);
    }
}

#[cfg(feature = "tui")]
fn reload_tui_preview(
    hot: &mut crepuscularity_tui::HotTemplate,
    force: bool,
) -> crepuscularity_tui::ReloadOutcome {
    use crepuscularity_tui::ReloadOutcome;
    let outcome = if force {
        match hot.template_mut().reload() {
            Ok(()) => ReloadOutcome::Reloaded,
            Err(error) => ReloadOutcome::Error(error),
        }
    } else {
        hot.poll_reload()
    };
    if outcome == ReloadOutcome::Reloaded {
        refresh_tui_preview_context(hot);
    }
    outcome
}

#[cfg(feature = "tui")]
fn refresh_tui_preview_context(hot: &mut crepuscularity_tui::HotTemplate) {
    let mut fresh = crepuscularity_tui::TemplateContext::new();
    if let Some(dir) = hot.template().path().parent() {
        load_tui_context_toml(&dir.join("context.toml"), &mut fresh);
    }
    // The CLI preview owns file variables; preserve include paths, slots and VFS.
    hot.template_mut().context_mut().vars = fresh.vars;
}

/// Minimal preview TOML loader (key=value, strings/bools/ints/floats).
#[cfg(feature = "tui")]
fn load_tui_context_toml(path: &Path, ctx: &mut crepuscularity_tui::TemplateContext) {
    use crepuscularity_tui::TemplateValue;
    let Ok(content) = std::fs::read_to_string(path) else {
        return;
    };
    for line in content.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(eq) = line.find('=') {
            let key = line[..eq].trim();
            let val = line[eq + 1..].trim();
            if val == "true" {
                ctx.set(key, TemplateValue::Bool(true));
            } else if val == "false" {
                ctx.set(key, TemplateValue::Bool(false));
            } else if let Ok(n) = val.parse::<i64>() {
                ctx.set(key, TemplateValue::Int(n));
            } else if let Ok(f) = val.parse::<f64>() {
                ctx.set(key, TemplateValue::Float(f));
            } else {
                ctx.set(key, strip_one_outer_quote_pair(val).to_string());
            }
        }
    }
}

/// Strip exactly one matching pair of `"`/`'` quotes from the outside of `s`.
///
/// Unlike `str::trim_matches('"').trim_matches('\'')` this preserves repeated
/// quotes inside the value, e.g. `"\"\"hi\"\""` → `\"hi\"` rather than `hi`.
#[cfg(feature = "tui")]
fn strip_one_outer_quote_pair(s: &str) -> &str {
    let bytes = s.as_bytes();
    if bytes.len() >= 2 {
        let first = bytes[0];
        let last = bytes[bytes.len() - 1];
        if (first == b'"' && last == b'"') || (first == b'\'' && last == b'\'') {
            // Slice on byte indices that we just verified are `"` / `'` — both
            // ASCII, so we are always on a UTF-8 char boundary.
            return &s[1..s.len() - 1];
        }
    }
    s
}

#[cfg(all(test, feature = "tui"))]
mod tests {
    use super::{refresh_tui_preview_context, reload_tui_preview, strip_one_outer_quote_pair};
    use crepuscularity_tui::{HotTemplate, ReloadOutcome, TemplateContext, TemplateValue};

    #[test]
    fn preview_refreshes_file_variables_without_replacing_context_metadata() {
        let dir = tempfile::tempdir().unwrap();
        let entry = dir.path().join("view.crepus");
        let context = dir.path().join("context.toml");
        std::fs::write(&entry, "span \"hello\"").unwrap();
        std::fs::write(&context, "name = 'old'\nremoved = true").unwrap();
        let mut hot = HotTemplate::watch(&entry).unwrap();
        let parent = std::sync::Arc::new(TemplateContext::new());
        hot.template_mut().context_mut().slot = Some((Vec::new(), parent.clone()));
        let files = hot.template().context().virtual_files.clone();
        let base_dir = hot.template().context().base_dir.clone();
        refresh_tui_preview_context(&mut hot);
        assert_eq!(hot.template().context().get_str("name"), "old");

        std::fs::write(
            &context,
            "name = \"new\"\ncount = 2\nratio = 2.5\nenabled = false",
        )
        .unwrap();
        assert_eq!(reload_tui_preview(&mut hot, true), ReloadOutcome::Reloaded);
        let ctx = hot.template().context();
        assert_eq!(ctx.get_str("name"), "new");
        assert!(matches!(ctx.get("count"), Some(TemplateValue::Int(2))));
        assert!(matches!(ctx.get("ratio"), Some(TemplateValue::Float(n)) if *n == 2.5));
        assert!(matches!(
            ctx.get("enabled"),
            Some(TemplateValue::Bool(false))
        ));
        assert!(ctx.get("removed").is_none());
        assert_eq!(ctx.base_dir, base_dir);
        assert!(std::sync::Arc::ptr_eq(&ctx.virtual_files, &files));
        assert!(std::sync::Arc::ptr_eq(
            &ctx.slot.as_ref().unwrap().1,
            &parent
        ));

        std::fs::remove_file(context).unwrap();
        assert_eq!(reload_tui_preview(&mut hot, true), ReloadOutcome::Reloaded);
        assert!(hot.template().context().vars.is_empty());
    }

    #[test]
    fn preview_automatic_reload_refreshes_variables_before_draw() {
        let dir = tempfile::tempdir().unwrap();
        let entry = dir.path().join("view.crepus");
        let context = dir.path().join("context.toml");
        std::fs::write(&entry, "span \"{name}\"").unwrap();
        std::fs::write(&context, "name = 'old'").unwrap();
        let mut hot = HotTemplate::watch(&entry).unwrap();
        refresh_tui_preview_context(&mut hot);
        let backend = ratatui::backend::TestBackend::new(30, 3);
        let mut terminal = ratatui::Terminal::new(backend).unwrap();
        terminal
            .draw(|frame| hot.draw_full(frame).unwrap())
            .unwrap();
        let initial_text: String = terminal
            .backend()
            .buffer()
            .content
            .iter()
            .map(|cell| cell.symbol())
            .collect();
        assert!(initial_text.contains("old"), "{initial_text}");
        std::fs::write(&context, "name = 'new'").unwrap();
        let started = std::time::Instant::now();
        loop {
            match reload_tui_preview(&mut hot, false) {
                ReloadOutcome::Reloaded => break,
                ReloadOutcome::Error(error) => panic!("reload failed: {error}"),
                ReloadOutcome::Unchanged => {}
            }
            assert!(
                started.elapsed() < std::time::Duration::from_secs(6),
                "context edit was not observed"
            );
            std::thread::sleep(std::time::Duration::from_millis(20));
        }
        assert_eq!(hot.template().context().get_str("name"), "new");
        terminal
            .draw(|frame| hot.draw_full(frame).unwrap())
            .unwrap();
        let text: String = terminal
            .backend()
            .buffer()
            .content
            .iter()
            .map(|cell| cell.symbol())
            .collect();
        assert!(text.contains("new"), "{text}");
        assert!(!text.contains("old"), "{text}");
    }

    #[test]
    fn preview_failed_reload_retains_source_and_file_variables() {
        let dir = tempfile::tempdir().unwrap();
        let entry = dir.path().join("view.crepus");
        let context = dir.path().join("context.toml");
        let source = "span \"{name}\"";
        std::fs::write(&entry, source).unwrap();
        std::fs::write(&context, "name = 'old'").unwrap();
        let mut hot = HotTemplate::watch(&entry).unwrap();
        refresh_tui_preview_context(&mut hot);
        std::fs::write(&context, "name = 'new'").unwrap();
        std::fs::remove_file(&entry).unwrap();
        assert!(matches!(
            reload_tui_preview(&mut hot, true),
            ReloadOutcome::Error(_)
        ));
        assert_eq!(hot.template().source(), source);
        assert_eq!(hot.template().context().get_str("name"), "old");

        std::fs::write(&entry, "<< invalid").unwrap();
        assert!(matches!(
            reload_tui_preview(&mut hot, true),
            ReloadOutcome::Error(_)
        ));
        assert_eq!(hot.template().source(), source);
        assert_eq!(hot.template().context().get_str("name"), "old");
    }

    #[test]
    fn strips_single_outer_double_quotes() {
        assert_eq!(strip_one_outer_quote_pair("\"hello\""), "hello");
    }

    #[test]
    fn strips_single_outer_single_quotes() {
        assert_eq!(strip_one_outer_quote_pair("'hi'"), "hi");
    }

    #[test]
    fn preserves_inner_quotes_when_repeated() {
        assert_eq!(
            strip_one_outer_quote_pair("\"\"keep\"\""),
            "\"keep\"",
            "only the outermost pair should be stripped"
        );
    }

    #[test]
    fn preserves_mismatched_quotes() {
        assert_eq!(strip_one_outer_quote_pair("\"hi'"), "\"hi'");
        assert_eq!(strip_one_outer_quote_pair("'hi\""), "'hi\"");
    }

    #[test]
    fn preserves_unquoted_value() {
        assert_eq!(strip_one_outer_quote_pair("plain"), "plain");
    }

    #[test]
    fn handles_short_inputs() {
        assert_eq!(strip_one_outer_quote_pair(""), "");
        assert_eq!(strip_one_outer_quote_pair("\""), "\"");
        assert_eq!(strip_one_outer_quote_pair("\"\""), "");
    }
}
