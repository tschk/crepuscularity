//! Generate Dart casing data from the same Rust Unicode tables used by core.
//! Run: rustc tool/generate_unicode_case.rs -O -o /tmp/crepus-unicode-case &&
//!      /tmp/crepus-unicode-case > lib/src/unicode_case_data.dart
use std::io::{self, Write};

fn escaped(value: &str) -> String {
    value
        .chars()
        .map(|c| format!("\\u{{{:x}}}", c as u32))
        .collect()
}

fn mappings(out: &mut impl Write, name: &str, entries: &[(u32, Vec<u32>)]) -> io::Result<()> {
    writeln!(out, "const _{name}Ranges = <int>[")?;
    let simple: Vec<_> = entries
        .iter()
        .filter_map(|(c, mapped)| {
            (mapped.len() == 1).then(|| (*c, i64::from(mapped[0]) - i64::from(*c)))
        })
        .collect();
    let mut index = 0;
    while index < simple.len() {
        let (start, delta) = simple[index];
        let stride = simple
            .get(index + 1)
            .filter(|(next, d)| *d == delta && *next - start <= 2)
            .map_or(1, |(next, _)| *next - start);
        let mut end = index + 1;
        while end < simple.len()
            && simple[end].1 == delta
            && simple[end].0 - simple[end - 1].0 == stride
        {
            end += 1;
        }
        writeln!(
            out,
            "  0x{start:x}, 0x{:x}, {stride}, {delta},",
            simple[end - 1].0
        )?;
        index = end;
    }
    writeln!(out, "];\nconst _{name}Expansions = <int, String>{{")?;
    for (c, mapped) in entries.iter().filter(|(_, mapped)| mapped.len() > 1) {
        let value: String = mapped.iter().map(|c| char::from_u32(*c).unwrap()).collect();
        writeln!(out, "  0x{c:x}: '{}',", escaped(&value))?;
    }
    writeln!(out, "}};\n")
}

fn ranges(out: &mut impl Write, name: &str, values: &[u32]) -> io::Result<()> {
    writeln!(out, "const _{name}Ranges = <int>[")?;
    let mut index = 0;
    while index < values.len() {
        let start = values[index];
        let mut end = index + 1;
        while end < values.len() && values[end] == values[end - 1] + 1 {
            end += 1;
        }
        writeln!(out, "  0x{start:x}, 0x{:x},", values[end - 1])?;
        index = end;
    }
    writeln!(out, "];")
}

fn main() -> io::Result<()> {
    let mut upper = Vec::new();
    let mut lower = Vec::new();
    let mut ignorable = Vec::new();
    let mut cased = Vec::new();
    for cp in 0..=0x10ffff {
        let Some(c) = char::from_u32(cp) else {
            continue;
        };
        let text = c.to_string();
        let u = text.to_uppercase();
        let l = text.to_lowercase();
        if u != text {
            upper.push((cp, u.chars().map(u32::from).collect()));
        }
        if l != text {
            lower.push((cp, l.chars().map(u32::from).collect()));
        }
        // Query Rust's final-sigma rule to obtain its exact context properties,
        // including Cased/Case_Ignorable overlap, without copying private tables.
        let is_cased = format!("AΣ{c}").to_lowercase().chars().nth(1) == Some('σ');
        if is_cased {
            cased.push(cp);
        } else if format!("AΣ{c}B").to_lowercase().chars().nth(1) == Some('σ') {
            ignorable.push(cp);
        }
    }
    let mut out = io::BufWriter::new(io::stdout().lock());
    let (major, minor, patch) = char::UNICODE_VERSION;
    writeln!(
        out,
        "// Generated by tool/generate_unicode_case.rs; do not edit."
    )?;
    writeln!(
        out,
        "// Unicode {major}.{minor}.{patch}, matching Rust core casing."
    )?;
    writeln!(out, "// dart format off")?;
    writeln!(out, "part of 'unicode_case.dart';\n")?;
    mappings(&mut out, "upper", &upper)?;
    mappings(&mut out, "lower", &lower)?;
    ranges(&mut out, "caseIgnorable", &ignorable)?;
    writeln!(out)?;
    ranges(&mut out, "cased", &cased)?;
    out.flush()
}
